"""Raw covariant radial-infall Fourier source in W0 conventions.

GM=1, transform T_hat=integral dt exp(+i omega t) T, inverse d omega/(2pi).
E is conserved particle energy; gamma>=1 for infall from infinity. The caller
supplies t_p(r) and the harmonic factor Y_lm*(Omega_p); kappa=1/M_Pl^2.
"""
import cmath
import math


def trajectory_derivative(r,gamma):
    f=1-2/r
    if r<=2 or gamma<1: raise ValueError('Require r>2 and gamma>=1')
    return -gamma/(f*math.sqrt(gamma*gamma-f))


def source_data(r,w,energy=1.,gamma=2.,time=0.,harmonic=1.,null=False):
    f=1-2/r;fp=2/r**2;fpp=-4/r**3
    if r<=2 or (not null and gamma<1):raise ValueError('Require r>2 and gamma>=1')
    phase=cmath.exp(1j*w*time)*harmonic
    if null:
        tt=energy/r**2*phase
        return {'tt':tt,'tr':tt/f,'rr':tt/f**2,'trace':0j,'trace_prime':0j,'trace_second':0j,
                'time_prime':-1/f}
    v=math.sqrt(gamma*gamma-f)
    tp=-gamma/(f*v)
    tpp=tp*(-fp/f+fp/(2*v*v))
    tau=-energy/(gamma*r*r*v)*phase
    logp=-2/r+fp/(2*v*v)+1j*w*tp
    logpp=2/r**2+fpp/(2*v*v)+fp*fp/(2*v**4)+1j*w*tpp
    return {'tt':energy*gamma/(r*r*v)*phase,'tr':energy/(r*r*f)*phase,
            'rr':energy*v/(gamma*r*r*f*f)*phase,
            'trace':tau,'trace_prime':tau*logp,'trace_second':tau*(logp*logp+logpp),'time_prime':tp}


def forcing(ell,r,w,mu,data,kappa=1.):
    """RHS for the coordinate-projected constrained operator generated by W3."""
    if mu<=0:raise ValueError('The finite-mass auxiliary constraints require mu>0')
    f=1-2/r;fp=2/r**2;L=ell*(ell+1)
    T,Tp,Tpp=(data[k] for k in ('trace','trace_prime','trace_second'))
    factor=kappa/(3*mu*mu)
    Htt=-w*w*T-f*fp*Tp/2
    Htr=-1j*w*(Tp-fp*T/(2*f))
    Hrr=Tpp+fp*Tp/(2*f)
    result={'tt':kappa*(data['tt']+f*T/3)+factor*Htt,
            'tr':kappa*data['tr']+factor*Htr,
            'rr':kappa*(data['rr']-T/(3*f))+factor*Hrr,
            'K':-kappa*T/3+factor*(f*Tp/r-L*T/(2*r*r)),
            'trace':factor*T,'trace_prime':factor*Tp,'trace_second':factor*Tpp,
            'div_0':-1j*w*factor*T,'div_0_prime':-1j*w*factor*Tp,
            'div_1':factor*Tp,'div_1_prime':factor*Tpp}
    if ell>=1:
        result.update({'tA':-1j*w*factor*T,'rA':factor*(Tp-T/r),
                       'div_2':factor*T,'div_2_prime':factor*Tp})
    if ell>=2:result['G']=factor*T/(2*r*r)
    return result
